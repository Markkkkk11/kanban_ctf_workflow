"""Small DB-API compatibility layer for local SQLite and hosted PostgreSQL.

Application SQL uses positional ? parameters. Values always remain bound parameters;
only the fixed application SQL syntax is translated for PostgreSQL.
"""
import re
import sqlite3

IDENTITY_TABLES = {'users', 'competitions', 'tasks', 'hypotheses', 'task_messages', 'messages', 'events', 'flag_jobs', 'task_files'}

class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

class Result:
    def __init__(self, cursor=None, values=None, lastrowid=None):
        self.cursor = cursor
        self.values = values
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount if cursor is not None else len(values or [])
    def fetchone(self):
        if self.values is not None: return self.values.pop(0) if self.values else None
        row = self.cursor.fetchone()
        return Row(row) if row is not None else None
    def fetchall(self):
        if self.values is not None:
            result=self.values;self.values=[];return result
        return [Row(r) for r in self.cursor.fetchall()]
    def __iter__(self): return iter(self.fetchall())

def translate(sql):
    sql=sql.strip().rstrip(';')
    sql=re.sub(r"'(?:''|[^'])*'|\?",lambda m:'%s' if m.group()=='?' else m.group(),sql)
    sql=re.sub(r'\bid INTEGER PRIMARY KEY\b','id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql,flags=re.I)
    if re.match(r'INSERT OR IGNORE ',sql,re.I):
        sql=re.sub(r'^INSERT OR IGNORE','INSERT',sql,flags=re.I)+' ON CONFLICT DO NOTHING'
    if sql.upper()=='BEGIN IMMEDIATE':sql='BEGIN'
    return sql

class PostgresConnection:
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.psycopg=psycopg
        # Disable prepared statements for transaction-pooling providers such as Neon.
        self.raw=psycopg.connect(url,autocommit=True,row_factory=dict_row,connect_timeout=10,prepare_threshold=None)
    @property
    def in_transaction(self):
        return self.raw.info.transaction_status != self.psycopg.pq.TransactionStatus.IDLE
    def execute(self, sql, params=()):
        statement=sql.strip()
        if statement.upper().startswith('PRAGMA TABLE_INFO('):
            table=re.fullmatch(r'PRAGMA table_info\((\w+)\)',statement,re.I).group(1)
            return Result(self.raw.execute('SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position',(table,)))
        if statement.upper().startswith('PRAGMA '): return Result(values=[])
        translated=translate(statement)
        if re.match(r'^(INSERT|UPDATE|DELETE|ALTER|CREATE)\b',translated,re.I) and not self.in_transaction:
            self.raw.execute('BEGIN')
        insert=re.match(r'INSERT INTO (\w+)\b',translated,re.I)
        returning_id=bool(insert and insert.group(1).lower() in IDENTITY_TABLES and not re.search(r'\bRETURNING\b',translated,re.I))
        if returning_id: translated+=' RETURNING id'
        try:
            cursor=self.raw.execute(translated,params or None)
            result=Result(cursor)
            if returning_id:
                row=cursor.fetchone();result.lastrowid=row['id'] if row else None
            return result
        except self.psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('Database constraint violation') from error
    def executemany(self, sql, params):
        if not self.in_transaction:self.raw.execute('BEGIN')
        try:
            cursor=self.raw.cursor();cursor.executemany(translate(sql),params);return Result(cursor)
        except self.psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('Database constraint violation') from error
    def executescript(self, script):
        # Schema scripts in this project contain no semicolons inside literals.
        for sql in script.split(';'):
            if sql.strip():self.execute(sql)
    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()

def connect(path, url=''):
    if url: return PostgresConnection(url)
    conn=sqlite3.connect(path,timeout=4)
    conn.row_factory=sqlite3.Row
    conn.execute('PRAGMA foreign_keys=ON')
    conn.execute('PRAGMA busy_timeout=4000')
    conn.execute('PRAGMA synchronous=NORMAL')
    return conn
